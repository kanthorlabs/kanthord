import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "../..");
const ENGINE = join(REPO, "engine/src");
const PAGE = join(REPO, "docs/reference/workbench/tools.md");
const CHECK_FLAG = "--check";

const SERVICES = [
  ["Agent", "agent", "agentOperations"],
  ["Gateway", "gateway", "gatewayOperations"],
  ["LLM", "llm", "llmOperations"],
  ["Mission", "mission", "missionOperations"],
  ["Project", "project", "projectOperations"],
  ["Repository", "repository", "repositoryOperations"],
  ["Scheduler", "scheduler", "schedulerOperations"],
  ["Storage", "storage", "storageOperations"],
  ["Workbench", "workbench", "workbenchOperations"],
  ["Worker", "worker", "workerOperations"],
];

const cell = (text) => text.replaceAll("|", "\\|").replaceAll("\n", " ");

async function sections() {
  const { toolOperations, toolName } = await import(
    join(ENGINE, "workbench/tools.ts")
  );
  const result = [];
  for (const [title, directory, exportName] of SERVICES) {
    const contract = await import(join(ENGINE, directory, "contract.ts"));
    const operations = contract[exportName];
    assert.ok(operations, `${directory}/contract.ts exports ${exportName}`);
    const tools = toolOperations(Object.values(operations)).sort((a, b) =>
      a.id.localeCompare(b.id),
    );
    if (tools.length > 0) result.push({ title, tools, toolName });
  }
  return result;
}

function render(groups) {
  const total = groups.reduce((sum, group) => sum + group.tools.length, 0);
  const changes = groups.reduce(
    (sum, group) => sum + group.tools.filter((tool) => tool.mutation).length,
    0,
  );
  const lines = [
    "# Workbench operation tools",
    "",
    "[Feature reference](../README.md)",
    "",
    "<!-- Generated by scripts/docs/workbench-tools.mjs. Run `make docs-tools` after an operation change. Do not edit by hand. -->",
    "",
    `An agent of a Workbench session can call ${total} KanthorD operations as tools. ${changes} of them change state and wait for the approval of the human. [How the native agent works](../../explanation/native-agent.md#tools) explains the selection rule and the exclusions.`,
    "",
    "The tool name is the operation id with each `.` replaced by `--`. A tool runs with the identity of the human who sent the last message.",
    "",
    "| Service | Tools | Change state |",
    "| ------- | ----- | ------------ |",
    ...groups.map(
      (group) =>
        `| [${group.title}](#${group.title.toLowerCase()}) | ${group.tools.length} | ${group.tools.filter((tool) => tool.mutation).length} |`,
    ),
  ];
  for (const group of groups) {
    lines.push(
      "",
      `## ${group.title}`,
      "",
      "| Tool | Route | Approval | Description |",
      "| ---- | ----- | -------- | ----------- |",
      ...group.tools.map(
        (tool) =>
          `| \`${group.toolName(tool.id)}\` | \`${tool.method} ${tool.path}\` | ${tool.mutation ? "Yes" : "No"} | ${cell(tool.description)} |`,
      ),
    );
  }
  return `${lines.join("\n")}\n`;
}

const page = render(await sections());
if (process.argv.includes(CHECK_FLAG)) {
  let current = "";
  try {
    current = readFileSync(PAGE, "utf8");
  } catch {}
  if (current !== page) {
    process.stderr.write(
      "docs/reference/workbench/tools.md is stale. Run make docs-tools\n",
    );
    process.exit(1);
  }
} else {
  mkdirSync(dirname(PAGE), { recursive: true });
  writeFileSync(PAGE, page);
  process.stdout.write(`${PAGE}\n`);
}
